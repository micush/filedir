#!/usr/bin/env python3
"""Writes the assembly of the blake3 package: hash4_amd64.s (SSSE3, four lanes) and hash8_amd64.s (AVX2, eight lanes).

Each file has two functions.  The chunk one hashes that many consecutive chunks of 1024 bytes at once: each of the 16 state words is a
vector with a lane for each chunk, so one run of the compression function does the work for all of them.  The parent one does the same
for that many parent nodes of the tree, each a single block of 64 bytes (two chaining values).  The 16 blocks of a chunk are looped
over; the seven rounds of a block are written out.  The state lives in the stack frame, and the message words are put there turned
around (words of one block of every lane side by side).

Run: python3 gen_amd64.py"""

perm = [2, 6, 3, 10, 7, 0, 4, 13, 1, 11, 12, 5, 9, 14, 15, 8]
sched = [list(range(16))]
for r in range(1, 7):
    sched.append([sched[-1][perm[i]] for i in range(16)])
ivs = [0x6A09E667, 0xBB67AE85, 0x3C6EF372, 0xA54FF53A, 0x510E527F, 0x9B05688C, 0x1F83D9AB, 0x5BE0CD19]

HEAD = "// Code generated by gen_amd64.py; DO NOT EDIT.\n\n#include \"textflag.h\"\n\n"


def gen_sse(kind):
    out = []
    e = out.append
    W = 16                               # bytes of a vector
    CV, V, M = 0, 128, 384
    FRAME = 640
    stride = 1024 if kind == "chunk" else 64
    nblocks = 16 if kind == "chunk" else 1
    name = "hash4ssse3" if kind == "chunk" else "parents4ssse3"

    def g(a, b, c, d, mx, my):
        for r, x in enumerate((a, b, c, d)):
            e(f"\tMOVOU {V+W*x}(SP), X{r}")
        e("\tPADDL X1, X0")
        e(f"\tMOVOU {M+W*mx}(SP), X4")
        e("\tPADDL X4, X0")
        e("\tPXOR X0, X3")
        e("\tPSHUFB X5, X3")              # rotate right 16
        e("\tPADDL X3, X2")
        e("\tPXOR X2, X1")
        e("\tMOVO X1, X4")
        e("\tPSRLL $12, X1")
        e("\tPSLLL $20, X4")
        e("\tPOR X4, X1")
        e("\tPADDL X1, X0")
        e(f"\tMOVOU {M+W*my}(SP), X4")
        e("\tPADDL X4, X0")
        e("\tPXOR X0, X3")
        e("\tPSHUFB X6, X3")              # rotate right 8
        e("\tPADDL X3, X2")
        e("\tPXOR X2, X1")
        e("\tMOVO X1, X4")
        e("\tPSRLL $7, X1")
        e("\tPSLLL $25, X4")
        e("\tPOR X4, X1")
        for r, x in enumerate((a, b, c, d)):
            e(f"\tMOVOU X{r}, {V+W*x}(SP)")

    def bcast(val):
        e(f"\tMOVL ${val:#x}, R10")
        e("\tMOVL R10, X0")
        e("\tPSHUFD $0, X0, X0")

    e(f"// func {name}(in *byte, ctr *[8]uint32, out *[8][4]uint32)")
    if kind == "chunk":
        e("// in: four chunks of 1024 bytes in a row.  ctr: the low words of the four chunk numbers, then the high words.")
    else:
        e("// in: four parent blocks of 64 bytes in a row (the two chaining values of each).  ctr is not used.")
    e("// out: the eight words of the four results, a vector for each word, a lane for each.")
    e(f"TEXT ·{name}(SB), 0, ${FRAME}-24")
    e("\tMOVQ in+0(FP), AX")
    e("\tMOVQ ctr+8(FP), BX")
    e("\tMOVQ out+16(FP), CX")
    e("\tMOVOU rot16<>(SB), X5")
    e("\tMOVOU rot8<>(SB), X6")
    for i, w in enumerate(ivs):          # the chaining value starts as the IV in every lane
        bcast(w)
        e(f"\tMOVOU X0, {CV+W*i}(SP)")
    e("\tXORQ DX, DX")                   # DX: the block
    e("block:")
    e("\tMOVQ DX, SI")
    e("\tSHLQ $6, SI")
    e("\tADDQ AX, SI")
    for j in range(4):                   # four groups of four words in a block
        for c in range(4):
            e(f"\tMOVOU {c*stride+16*j}(SI), X{c}")
        e("\tMOVO X0, X4")
        e("\tPUNPCKLLQ X1, X4")
        e("\tMOVO X2, X7")
        e("\tPUNPCKLLQ X3, X7")
        e("\tPUNPCKHLQ X1, X0")
        e("\tPUNPCKHLQ X3, X2")
        e("\tMOVO X4, X1")
        e("\tPUNPCKLQDQ X7, X4")
        e("\tPUNPCKHQDQ X7, X1")
        e("\tMOVO X0, X3")
        e("\tPUNPCKLQDQ X2, X0")
        e("\tPUNPCKHQDQ X2, X3")
        for k, r in enumerate((4, 1, 0, 3)):
            e(f"\tMOVOU X{r}, {M+W*(4*j+k)}(SP)")
    for i in range(8):
        e(f"\tMOVOU {CV+W*i}(SP), X0")
        e(f"\tMOVOU X0, {V+W*i}(SP)")
    for i in range(4):
        bcast(ivs[i])
        e(f"\tMOVOU X0, {V+W*(8+i)}(SP)")
    if kind == "chunk":
        e("\tMOVOU (BX), X0")
        e(f"\tMOVOU X0, {V+W*12}(SP)")
        e("\tMOVOU 16(BX), X0")
        e(f"\tMOVOU X0, {V+W*13}(SP)")
    else:
        e("\tPXOR X0, X0")
        e(f"\tMOVOU X0, {V+W*12}(SP)")
        e(f"\tMOVOU X0, {V+W*13}(SP)")
    bcast(64)
    e(f"\tMOVOU X0, {V+W*14}(SP)")
    if kind == "chunk":
        e("\tXORL R9, R9")               # chunk start on the first block, chunk end on the last
        e("\tTESTQ DX, DX")
        e("\tJNE notfirst")
        e("\tORL $1, R9")
        e("notfirst:")
        e("\tCMPQ DX, $15")
        e("\tJNE notlast")
        e("\tORL $2, R9")
        e("notlast:")
    else:
        e("\tMOVL $4, R9")               # parent
    e("\tMOVL R9, X0")
    e("\tPSHUFD $0, X0, X0")
    e(f"\tMOVOU X0, {V+W*15}(SP)")
    for r in range(7):
        s = sched[r]
        g(0, 4, 8, 12, s[0], s[1])
        g(1, 5, 9, 13, s[2], s[3])
        g(2, 6, 10, 14, s[4], s[5])
        g(3, 7, 11, 15, s[6], s[7])
        g(0, 5, 10, 15, s[8], s[9])
        g(1, 6, 11, 12, s[10], s[11])
        g(2, 7, 8, 13, s[12], s[13])
        g(3, 4, 9, 14, s[14], s[15])
    for i in range(8):
        e(f"\tMOVOU {V+W*i}(SP), X0")
        e(f"\tMOVOU {V+W*(i+8)}(SP), X1")
        e("\tPXOR X1, X0")
        e(f"\tMOVOU X0, {CV+W*i}(SP)")
    e("\tINCQ DX")
    e(f"\tCMPQ DX, ${nblocks}")
    e("\tJNE block")
    for i in range(8):
        e(f"\tMOVOU {CV+W*i}(SP), X0")
        e(f"\tMOVOU X0, {W*i}(CX)")
    e("\tRET")
    e("")
    return "\n".join(out)


def gen_avx2(kind):
    out = []
    e = out.append
    W = 32
    CV, V, M = 0, 256, 768
    FRAME = 1280
    stride = 1024 if kind == "chunk" else 64
    nblocks = 16 if kind == "chunk" else 1
    name = "hash8avx2" if kind == "chunk" else "parents8avx2"

    def g(a, b, c, d, mx, my):
        for r, x in enumerate((a, b, c, d)):
            e(f"\tVMOVDQU {V+W*x}(SP), Y{r}")
        e("\tVPADDD Y1, Y0, Y0")
        e(f"\tVPADDD {M+W*mx}(SP), Y0, Y0")
        e("\tVPXOR Y0, Y3, Y3")
        e("\tVPSHUFB Y5, Y3, Y3")
        e("\tVPADDD Y3, Y2, Y2")
        e("\tVPXOR Y2, Y1, Y1")
        e("\tVPSLLD $20, Y1, Y4")
        e("\tVPSRLD $12, Y1, Y1")
        e("\tVPOR Y4, Y1, Y1")
        e("\tVPADDD Y1, Y0, Y0")
        e(f"\tVPADDD {M+W*my}(SP), Y0, Y0")
        e("\tVPXOR Y0, Y3, Y3")
        e("\tVPSHUFB Y6, Y3, Y3")
        e("\tVPADDD Y3, Y2, Y2")
        e("\tVPXOR Y2, Y1, Y1")
        e("\tVPSLLD $25, Y1, Y4")
        e("\tVPSRLD $7, Y1, Y1")
        e("\tVPOR Y4, Y1, Y1")
        for r, x in enumerate((a, b, c, d)):
            e(f"\tVMOVDQU Y{r}, {V+W*x}(SP)")

    def bcast(val):
        e(f"\tMOVL ${val:#x}, R10")
        e("\tVMOVD R10, X0")
        e("\tVPBROADCASTD X0, Y0")

    e(f"// func {name}(in *byte, ctr *[16]uint32, out *[8][8]uint32)")
    if kind == "chunk":
        e("// in: eight chunks of 1024 bytes in a row.  ctr: the low words of the eight chunk numbers, then the high words.")
    else:
        e("// in: eight parent blocks of 64 bytes in a row.  ctr is not used.")
    e(f"TEXT ·{name}(SB), 0, ${FRAME}-24")
    e("\tMOVQ in+0(FP), AX")
    e("\tMOVQ ctr+8(FP), BX")
    e("\tMOVQ out+16(FP), CX")
    e("\tVMOVDQU rot16x2<>(SB), Y5")
    e("\tVMOVDQU rot8x2<>(SB), Y6")
    for i, w in enumerate(ivs):
        bcast(w)
        e(f"\tVMOVDQU Y0, {CV+W*i}(SP)")
    e("\tXORQ DX, DX")
    e("block:")
    e("\tMOVQ DX, SI")
    e("\tSHLQ $6, SI")
    e("\tADDQ AX, SI")
    for j in range(2):                   # two groups of eight words in a block
        for c in range(8):
            e(f"\tVMOVDQU {c*stride+32*j}(SI), Y{c}")
        e("\tVPUNPCKLDQ Y1, Y0, Y8")
        e("\tVPUNPCKHDQ Y1, Y0, Y9")
        e("\tVPUNPCKLDQ Y3, Y2, Y10")
        e("\tVPUNPCKHDQ Y3, Y2, Y11")
        e("\tVPUNPCKLDQ Y5, Y4, Y12")
        e("\tVPUNPCKHDQ Y5, Y4, Y13")
        e("\tVPUNPCKLDQ Y7, Y6, Y14")
        e("\tVPUNPCKHDQ Y7, Y6, Y15")
        e("\tVPUNPCKLQDQ Y10, Y8, Y0")
        e("\tVPUNPCKHQDQ Y10, Y8, Y1")
        e("\tVPUNPCKLQDQ Y11, Y9, Y2")
        e("\tVPUNPCKHQDQ Y11, Y9, Y3")
        e("\tVPUNPCKLQDQ Y14, Y12, Y4")
        e("\tVPUNPCKHQDQ Y14, Y12, Y5")
        e("\tVPUNPCKLQDQ Y15, Y13, Y6")
        e("\tVPUNPCKHQDQ Y15, Y13, Y7")
        for w in range(4):
            e(f"\tVPERM2I128 $0x20, Y{w+4}, Y{w}, Y8")
            e(f"\tVPERM2I128 $0x31, Y{w+4}, Y{w}, Y9")
            e(f"\tVMOVDQU Y8, {M+W*(8*j+w)}(SP)")
            e(f"\tVMOVDQU Y9, {M+W*(8*j+w+4)}(SP)")
        e("\tVMOVDQU rot16x2<>(SB), Y5")   # the masks were in Y5 and Y6
        e("\tVMOVDQU rot8x2<>(SB), Y6")
    for i in range(8):
        e(f"\tVMOVDQU {CV+W*i}(SP), Y0")
        e(f"\tVMOVDQU Y0, {V+W*i}(SP)")
    for i in range(4):
        bcast(ivs[i])
        e(f"\tVMOVDQU Y0, {V+W*(8+i)}(SP)")
    if kind == "chunk":
        e("\tVMOVDQU (BX), Y0")
        e(f"\tVMOVDQU Y0, {V+W*12}(SP)")
        e("\tVMOVDQU 32(BX), Y0")
        e(f"\tVMOVDQU Y0, {V+W*13}(SP)")
    else:
        e("\tVPXOR Y0, Y0, Y0")
        e(f"\tVMOVDQU Y0, {V+W*12}(SP)")
        e(f"\tVMOVDQU Y0, {V+W*13}(SP)")
    bcast(64)
    e(f"\tVMOVDQU Y0, {V+W*14}(SP)")
    if kind == "chunk":
        e("\tXORL R9, R9")
        e("\tTESTQ DX, DX")
        e("\tJNE notfirst")
        e("\tORL $1, R9")
        e("notfirst:")
        e("\tCMPQ DX, $15")
        e("\tJNE notlast")
        e("\tORL $2, R9")
        e("notlast:")
    else:
        e("\tMOVL $4, R9")
    e("\tVMOVD R9, X0")
    e("\tVPBROADCASTD X0, Y0")
    e(f"\tVMOVDQU Y0, {V+W*15}(SP)")
    for r in range(7):
        s = sched[r]
        g(0, 4, 8, 12, s[0], s[1])
        g(1, 5, 9, 13, s[2], s[3])
        g(2, 6, 10, 14, s[4], s[5])
        g(3, 7, 11, 15, s[6], s[7])
        g(0, 5, 10, 15, s[8], s[9])
        g(1, 6, 11, 12, s[10], s[11])
        g(2, 7, 8, 13, s[12], s[13])
        g(3, 4, 9, 14, s[14], s[15])
    for i in range(8):
        e(f"\tVMOVDQU {V+W*i}(SP), Y0")
        e(f"\tVPXOR {V+W*(i+8)}(SP), Y0, Y0")
        e(f"\tVMOVDQU Y0, {CV+W*i}(SP)")
    e("\tINCQ DX")
    e(f"\tCMPQ DX, ${nblocks}")
    e("\tJNE block")
    for i in range(8):
        e(f"\tVMOVDQU {CV+W*i}(SP), Y0")
        e(f"\tVMOVDQU Y0, {W*i}(CX)")
    e("\tVZEROUPPER")
    e("\tRET")
    e("")
    return "\n".join(out)


sse_data = """DATA rot16<>+0(SB)/8, $0x0504070601000302
DATA rot16<>+8(SB)/8, $0x0D0C0F0E09080B0A
GLOBL rot16<>(SB), RODATA|NOPTR, $16
DATA rot8<>+0(SB)/8, $0x0407060500030201
DATA rot8<>+8(SB)/8, $0x0C0F0E0D080B0A09
GLOBL rot8<>(SB), RODATA|NOPTR, $16

"""
avx_data = """DATA rot16x2<>+0(SB)/8, $0x0504070601000302
DATA rot16x2<>+8(SB)/8, $0x0D0C0F0E09080B0A
DATA rot16x2<>+16(SB)/8, $0x0504070601000302
DATA rot16x2<>+24(SB)/8, $0x0D0C0F0E09080B0A
GLOBL rot16x2<>(SB), RODATA|NOPTR, $32
DATA rot8x2<>+0(SB)/8, $0x0407060500030201
DATA rot8x2<>+8(SB)/8, $0x0C0F0E0D080B0A09
DATA rot8x2<>+16(SB)/8, $0x0407060500030201
DATA rot8x2<>+24(SB)/8, $0x0C0F0E0D080B0A09
GLOBL rot8x2<>(SB), RODATA|NOPTR, $32

"""
open("hash4_amd64.s", "w").write(HEAD + sse_data + gen_sse("chunk") + "\n" + gen_sse("parent"))
open("hash8_amd64.s", "w").write(HEAD + avx_data + gen_avx2("chunk") + "\n" + gen_avx2("parent"))
